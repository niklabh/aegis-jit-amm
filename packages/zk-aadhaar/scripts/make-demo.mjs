#!/usr/bin/env node
// SPDX-License-Identifier: MIT
// Generates the built-in sample QR codes:
//   • a fresh RSA-2048 "demo signer" and self-signed certificate (via openssl),
//   • a correctly signed sample and a tampered copy of it (fictional data,
//     synthetic avatar photo, V5 layout like current e-Aadhaar),
//   • src/lib/demo/{demo-certificate,samples}.ts and public/samples/*.png.
// The private key only ever lives in a temp directory and is deleted at the end,
// so nobody can mint new QR codes that pass as "signed by the demo key".
import { execFileSync } from "node:child_process";
import { createHash, sign, X509Certificate } from "node:crypto";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildSignedData, replaceField, toQrDigits } from "./lib/secure-qr-builder.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const work = mkdtempSync(join(tmpdir(), "zkaadhaar-demo-"));

try {
  execFileSync(
    "openssl",
    [
      "req", "-x509", "-newkey", "rsa:2048", "-nodes", "-sha256", "-days", "3650",
      "-keyout", join(work, "key.pem"), "-out", join(work, "cert.pem"),
      "-subj", "/O=zkAadhaar demo (NOT UIDAI)/CN=zkAadhaar demo signer - NOT UIDAI",
    ],
    { stdio: "ignore" },
  );
  const privateKey = readFileSync(join(work, "key.pem"));
  const certificate = new X509Certificate(readFileSync(join(work, "cert.pem")));

  const now = new Date();
  const stamp = [
    now.getFullYear(), now.getMonth() + 1, now.getDate(), now.getHours(), now.getMinutes(), now.getSeconds(),
  ].map((n, i) => String(n).padStart(i === 0 ? 4 : 2, "0")).join("") + "000";

  const fields = {
    version: "V5",
    indicator: "3",
    referenceId: `1234${stamp}`,
    name: "Ananya Sample",
    dob: "15-08-1994",
    gender: "F",
    careOf: "D/O: Ravi Sample",
    district: "Bengaluru Urban",
    landmark: "Near Cubbon Park",
    house: "No. 42, 2nd Floor",
    location: "Sample Nagar",
    pincode: "560001",
    postOffice: "Bangalore GPO",
    state: "Karnataka",
    street: "MG Road",
    subDistrict: "Bangalore North",
    vtc: "Bengaluru",
    mobile: "XXXXXX4321",
    photo: new Uint8Array(readFileSync(join(root, "scripts", "assets", "demo-photo.j2k"))),
    maskedEmail: "axxxxxxxe@exxxxxx.com",
  };

  const signedData = buildSignedData(fields);
  const signature = sign("sha256", signedData, privateKey); // RSASSA-PKCS1-v1_5
  const signedDigits = toQrDigits(signedData, signature);
  // Tamper: change the date of birth (field 4 in the versioned layout), keep the signature.
  const tamperedDigits = toQrDigits(replaceField(signedData, 4, "15-08-1984"), signature);

  const fingerprint = createHash("sha256").update(certificate.raw).digest("hex").toUpperCase().match(/../g).join(":");
  mkdirSync(join(root, "src", "lib", "demo"), { recursive: true });
  writeFileSync(
    join(root, "src", "lib", "demo", "demo-certificate.ts"),
    `// AUTO-GENERATED by scripts/make-demo.mjs — do not edit by hand.
// Self-signed certificate of the key that signed the built-in sample QR codes.
// It is NOT a UIDAI key: QR codes it signed are reported as "untrusted key".

export const DEMO_CERTIFICATE = {
  sha256: ${JSON.stringify(fingerprint)},
  pem: \`${certificate.toString().trim()}\`,
} as const;
`,
  );
  writeFileSync(
    join(root, "src", "lib", "demo", "samples.ts"),
    `// AUTO-GENERATED by scripts/make-demo.mjs — do not edit by hand.
// Fictional sample Secure QR payloads (V5 layout, synthetic photo).
// "signed" verifies against the demo key; "tampered" is the same payload with
// the date of birth changed after signing, so its signature no longer matches.

export const DEMO_QR_SIGNED = ${JSON.stringify(signedDigits)};

export const DEMO_QR_TAMPERED = ${JSON.stringify(tamperedDigits)};
`,
  );

  console.log(`Demo signer: ${certificate.subject.replace(/\n/g, ", ")}`);
  console.log(`  SHA-256 ${fingerprint}`);
  console.log(`Samples: signed ${signedDigits.length} digits, tampered ${tamperedDigits.length} digits`);

  let QRCode;
  try {
    ({ default: QRCode } = await import("qrcode"));
  } catch {
    console.warn("qrcode is not installed — skipped public/samples/*.png (run npm install, then this script again).");
  }
  if (QRCode) {
    mkdirSync(join(root, "public", "samples"), { recursive: true });
    for (const [name, digits] of [["demo-signed-qr.png", signedDigits], ["demo-tampered-qr.png", tamperedDigits]]) {
      await QRCode.toFile(join(root, "public", "samples", name), digits, { errorCorrectionLevel: "M", margin: 4, scale: 6 });
    }
    console.log(`QR images: public/samples/ (version ${QRCode.create(signedDigits, { errorCorrectionLevel: "M" }).version})`);
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
