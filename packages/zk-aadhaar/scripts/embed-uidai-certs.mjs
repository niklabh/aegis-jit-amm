#!/usr/bin/env node
// SPDX-License-Identifier: MIT
// Regenerates src/lib/aadhaar/uidai-certificates.ts from the official UIDAI
// certificate files in certs/uidai/. To add a rotated key: download the new
// uidai_offline_publickey_*.cer from https://uidai.gov.in/en/data-and-download
// ("Offline e-KYC public key certificates"), compare its fingerprint with the
// one UIDAI publishes, drop it into certs/uidai/ and run `npm run certs:embed`.
import { X509Certificate } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const certDir = join(root, "certs", "uidai");
const outFile = join(root, "src", "lib", "aadhaar", "uidai-certificates.ts");
const SOURCE_BASE = "https://backend.uidai.gov.in/get/files/media/document/2026-07/";

const certificates = readdirSync(certDir)
  .filter((name) => /\.(cer|crt|pem|der)$/i.test(name))
  .map((fileName) => {
    const x509 = new X509Certificate(readFileSync(join(certDir, fileName)));
    const subjectCN = /(?:^|\n)CN=([^\n]+)/.exec(x509.subject)?.[1] ?? x509.subject;
    const issuerCN = /(?:^|\n)CN=([^\n]+)/.exec(x509.issuer)?.[1] ?? x509.issuer;
    const keyBits = x509.publicKey.asymmetricKeyDetails?.modulusLength;
    if (x509.publicKey.asymmetricKeyType !== "rsa" || keyBits !== 2048) {
      throw new Error(`${fileName}: expected an RSA-2048 key, got ${x509.publicKey.asymmetricKeyType}/${keyBits}`);
    }
    return {
      fileName,
      sourceUrl: SOURCE_BASE + fileName,
      subjectCN,
      issuerCN,
      notBefore: new Date(x509.validFrom).toISOString(),
      notAfter: new Date(x509.validTo).toISOString(),
      sha256: x509.fingerprint256,
      pem: x509.toString().replace(/\r\n/g, "\n").trim(),
    };
  })
  .sort((a, b) => b.notBefore.localeCompare(a.notBefore));

const body = certificates
  .map(
    (c) => `  {
    fileName: ${JSON.stringify(c.fileName)},
    sourceUrl: ${JSON.stringify(c.sourceUrl)},
    subjectCN: ${JSON.stringify(c.subjectCN)},
    issuerCN: ${JSON.stringify(c.issuerCN)},
    notBefore: ${JSON.stringify(c.notBefore)},
    notAfter: ${JSON.stringify(c.notAfter)},
    sha256: ${JSON.stringify(c.sha256)},
    pem: \`${c.pem}\`,
  },`,
  )
  .join("\n");

writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/embed-uidai-certs.mjs from certs/uidai/*.cer — do not edit by hand.
//
// Official UIDAI public key certificates for validating the digital signature
// of Aadhaar Paperless Offline e-KYC and Secure QR codes, as listed on
// https://uidai.gov.in/en/data-and-download ("Offline e-KYC public key certificates").
// Expired certificates are kept on purpose: a QR printed while a key was
// current stays validly signed by that key.

export interface EmbeddedCertificate {
  fileName: string;
  sourceUrl: string;
  subjectCN: string;
  issuerCN: string;
  notBefore: string;
  notAfter: string;
  /** SHA-256 fingerprint of the DER certificate. */
  sha256: string;
  pem: string;
}

export const UIDAI_CERTIFICATES: readonly EmbeddedCertificate[] = [
${body}
];
`,
);

console.log(`Embedded ${certificates.length} UIDAI certificates into ${outFile}`);
for (const c of certificates) {
  console.log(`  ${c.fileName.padEnd(40)} ${c.notBefore.slice(0, 10)} → ${c.notAfter.slice(0, 10)}  ${c.sha256}`);
}
